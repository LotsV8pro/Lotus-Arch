#!/usr/bin/env bash
set -euo pipefail

STEAM_DIRS=(
    "$HOME/.local/share/Steam/steamapps"
    "$HOME/.steam/steam/steamapps"
)
OUT="$HOME/hakuspace-control/niri-steam-games.kdl"

EXCLUDE_RE='(Steam Linux Runtime|Proton Experimental|Proton Hotfix|Steamworks Common|Redistributables)'

generate() {
    local manifests=()
    local dir
    for dir in "${STEAM_DIRS[@]}"; do
        [ -d "$dir" ] || continue
        while IFS= read -r -d '' f; do
            manifests+=("$f")
        done < <(find "$dir" -maxdepth 1 -name 'appmanifest_*.acf' -print0 2>/dev/null)
    done

    local tmp
    tmp="$(mktemp)"
    {
        printf '// GENERATED by haku_steam_games.sh at %s -- DO NOT EDIT\n' "$(date '+%F %T')"
        printf '// window-rules VRR por juego de Steam (reload: niri msg action load-config-file)\n\n'

        local f appid name
        local -A seen=()
        for f in "${manifests[@]}"; do
            appid="$(basename "$f" | sed 's/^appmanifest_//; s/\.acf$//')"
            name="$(grep -m1 '"name"' "$f" | sed 's/^[[:space:]]*"name"[[:space:]]*"\(.*\)"[[:space:]]*$/\1/')"
            [ -n "$name" ] || continue
            if printf '%s' "$name" | grep -qE "$EXCLUDE_RE"; then
                continue
            fi
            [ -z "${seen[$appid]:-}" ] || continue
            seen[$appid]=1
            printf 'window-rule {\n'
            printf '    match app-id=r#"^steam_app_%s$"# title=r#"%s"#\n' "$appid" "$name"
            printf '    variable-refresh-rate true\n'
            printf '}\n\n'
        done
    } > "$tmp"

    if [ -f "$OUT" ] && cmp -s "$OUT" "$tmp"; then
        rm -f "$tmp"
        return 0
    fi
    mv "$tmp" "$OUT"
    printf '[haku_steam_games] regenerated %s\n' "$OUT"
    if command -v niri >/dev/null 2>&1; then
        niri msg action load-config-file >/dev/null 2>&1 || true
    fi
}

generate

if [ "${1:-}" = "--watch" ]; then
    while :; do
        sleep 30
        generate
    done
fi